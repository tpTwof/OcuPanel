    "改写后的内容必须由原始病例、给定参考资料或声明的软件边界支持。"
    "不要求指南记载患者的原始检查值，也不否定基于病例与通用诊断要素的审慎解释。"
    "你从不新增资料以外的数字、剂量或结论，也从不改动未被点名的句子。"
